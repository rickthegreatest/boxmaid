/// A grapheme as ASCII, filling as many cells (1 or 2).
pub(crate) fn ascii_grapheme(g: &str, cells: usize) -> String {
    let first = g.chars().next().unwrap_or(' ');
    if g.chars().count() == 1 && (first as u32) < 0x80 {
        return g.to_string();
    }
    let mut s = ascii_for(first).unwrap_or("?").to_string();
    while s.len() < cells {
        s.push('?');
    }
    s
}
