// asciiGrapheme is a grapheme as ASCII, filling as many cells (1 or 2).
func asciiGrapheme(g string, cells int) string {
	r := []rune(g)
	if len(r) == 1 && r[0] < 0x80 {
		return g
	}
	s, ok := asciiFor[r[0]]
	if !ok {
		s = "?"
	}
	for len(s) < cells {
		s += "?"
	}
	return s
}
